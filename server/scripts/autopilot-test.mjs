// Verifies the real scheduler autopilot path: a due slot within lead-time makes
// the tick generate a post (trigger=CRON) under the master + connection guards,
// then publishing happens when the slot time arrives.
const BASE = 'http://localhost:3001/api/v1';
let token = '';
async function api(m, p, b) { const r = await fetch(BASE + p, { method: m, headers: { 'content-type': 'application/json', ...(token ? { authorization: `Bearer ${token}` } : {}) }, body: b ? JSON.stringify(b) : undefined }); return { status: r.status, json: await r.json().catch(() => ({})) }; }
async function login() { for (const pw of ['golu9588', 'Vansh-Secure-2026!']) { let r = await api('POST', '/auth/login', { username: 'admin', password: pw }); if (r.json.accessToken) { token = r.json.accessToken; if (r.json.mustChangePassword) { r = await api('POST', '/auth/change-password', { currentPassword: pw, newPassword: 'Vansh-Secure-2026!' }); token = r.json.accessToken; } return true; } } return false; }
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function main() {
  if (!await login()) { console.log('login failed'); process.exit(1); }
  const conns = (await api('GET', '/connections')).json.data;
  const c = conns.find((x) => x.platform === 'LINKEDIN'); // simulated publish, safe

  // Slot ~70s out, today, so generation fires immediately (within lead) and
  // publish fires on the tick after the slot time.
  const now = new Date();
  const slot = new Date(now.getTime() + 70 * 1000);
  const hh = String(slot.getHours()).padStart(2, '0');
  const mm = String(slot.getMinutes()).padStart(2, '0');
  await api('PUT', `/connections/${c.id}/schedule`, { isEnabled: true, slots: [{ dayOfWeek: slot.getDay(), time: `${hh}:${mm}` }], maxPerDay: 20, leadTimeMinutes: 180, quietHours: {}, categoryRatio: { PRODUCT: 50, KNOWLEDGE: 50 } });
  await api('PUT', `/connections/${c.id}/mode`, { mode: 'AUTOPILOT' });
  await api('PUT', '/automation/master', { mode: 'AUTOPILOT' });
  console.log(`Set ${c.label} → AUTOPILOT with a slot at ${hh}:${mm} (in ~70s). Master → AUTOPILOT.`);

  const before = (await api('GET', `/posts?connectionId=${c.id}&limit=100`)).json.meta.total;

  // Wait for the tick to auto-generate.
  let generated = null;
  for (let i = 0; i < 8; i++) {
    await sleep(4000);
    const posts = (await api('GET', `/posts?connectionId=${c.id}&limit=100`)).json.data;
    generated = posts.find((p) => p.generationMeta?.runId && ['SCHEDULED', 'GENERATING', 'NEEDS_REVIEW'].includes(p.status) && new Date(p.createdAt) > now);
    if (generated) break;
  }
  console.log(generated ? `✓ Autopilot generated a post: "${generated.title}" (status ${generated.status}, SEO ${generated.seoScore}, scheduled ${generated.scheduledAt})` : '✗ No post generated by autopilot within 32s');
  if (!generated) process.exit(1);

  // Wait for publish once the slot time passes.
  let published = false;
  for (let i = 0; i < 20; i++) {
    await sleep(5000);
    const p = (await api('GET', `/posts/${generated.id}`)).json.data;
    if (p.status === 'PUBLISHED') { published = true; console.log(`✓ Autopilot published it → ${p.externalUrl}`); break; }
    if (p.status === 'FAILED') { console.log('✗ publish failed'); break; }
  }
  if (!published) console.log('… still scheduled (slot not reached yet in the wait window) — generation guard path verified regardless.');

  // Reset to a calm state for handoff.
  await api('PUT', '/automation/master', { mode: 'MANUAL' });
  await api('PUT', `/connections/${c.id}/mode`, { mode: 'SHADOW' });
  console.log('Reset master→MANUAL, connection→SHADOW.');
}
main().catch((e) => { console.error(e); process.exit(2); });
